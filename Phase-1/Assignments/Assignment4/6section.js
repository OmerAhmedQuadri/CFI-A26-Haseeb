switch (item) {
    case 'apple':
        console.log('It is a fruit')
        break
    case 'carrot':
        console.log('It is a vegetable')
        break
    case 'tomato':
        console.log('It is a vegetable')
        break
    default:
        console.log('Unknown item')
}


